function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function replaceWords(text, map) {
  let out = String(text);
  out = out.replace(/([A-Za-z]+)'s\b/gi, "$1");
  const entries = Object.entries(map).sort((a, b) => b[0].length - a[0].length);
  for (const [english, hindi] of entries) {
    if (!english) continue;
    const pattern = new RegExp(`\\b${escapeRegExp(english)}\\b`, "gi");
    out = out.replace(pattern, hindi);
  }
  return out;
}

function translateStoryText(text) {
  let out = String(text);
  SENTENCE_PATTERNS.forEach(([pattern, replacement]) => {
    out = out.replace(pattern, replacement);
  });
  out = replaceWords(out, NAME_MAP);
  out = replaceWords(out, WORD_MAP);
  out = replaceWords(out, COMMON_WORD_MAP);
  out = out.replace(/\s+/g, " ").replace(/\s([,.!?])/g, "$1").trim();
  return out;
}

function translateQuestionText(question) {
  let out = String(question);
  QUESTION_PATTERNS.forEach(([pattern, replacement]) => {
    out = out.replace(pattern, replacement);
  });
  out = replaceWords(out, NAME_MAP);
  out = replaceWords(out, WORD_MAP);
  out = replaceWords(out, COMMON_WORD_MAP);
  out = out.replace(/\s+/g, " ").replace(/\s([,.!?])/g, "$1").trim();
  return out;
}

function translateOptionText(option) {
  let out = String(option);
  out = replaceWords(out, WORD_MAP);
  out = replaceWords(out, NAME_MAP);
  out = replaceWords(out, COMMON_WORD_MAP);
  out = out.replace(/\bA\s+/gi, "")
    .replace(/\bAn\s+/gi, "")
    .replace(/\bHis\s+/gi, "उसका ")
    .replace(/\bHer\s+/gi, "उसकी ")
    .replace(/\bTheir\s+/gi, "उनका ")
    .replace(/\bThe\b/gi, "")
    .replace(/\s+/g, " ")
    .replace(/\s([,.!?])/g, "$1")
    .trim();
  return out;
}

function buildHindiStoryContent(content) {
  return Object.fromEntries(
    Object.entries(content).map(([level, stories]) => [
      level,
      stories.map((story) => ({
        ...story,
        text: translateStoryText(story.text),
        questions: story.questions.map((item) => ({
          ...item,
          question: translateQuestionText(item.question),
          options: item.options.map((option) => translateOptionText(option)),
        })),
      })),
    ]),
  );
}

